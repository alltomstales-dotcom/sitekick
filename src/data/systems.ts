/** Reachability matrix: from row system to column system */
export function getReachability(fromId: string, toId: string): Reachability {
  if (fromId === toId) return 'path';

  const direct = EDGES.find(
    (e) =>
      (e.source === fromId && e.target === toId) ||
      (e.source === toId && e.target === fromId),
  );
  if (direct) {
    if (direct.status === 'active') return 'path';
    if (direct.status === 'degraded' || direct.status === 'constrained') return 'constrained';
    if (direct.status === 'broken' || direct.status === 'missing') return 'none';
  }

  // 1-hop via Rhapsody / edge / MPI / HIE
  const hubs = ['rhapsody', 'rhapsody-edge', 'mpi', 'hie-gw', 'ahn-hub', 'ext-hub'];
  for (const hub of hubs) {
    const a = EDGES.find(
      (e) =>
        (e.source === fromId && e.target === hub) ||
        (e.source === hub && e.target === fromId),
    );
    const b = EDGES.find(
      (e) =>
        (e.source === toId && e.target === hub) ||
        (e.source === hub && e.target === toId),
    );
    if (a && b) {
      const worst = [a.status, b.status];
      if (worst.every((s) => s === 'active')) return 'path';
      if (worst.some((s) => s === 'broken' || s === 'missing')) return 'none';
      return 'constrained';
    }
  }

  const knownNone = [
    ['upmc', 'mpi'],
    ['tower-health', 'mpi'],
    ['wellspan', 'hmk-claims'],
  ];
  for (const [a, b] of knownNone) {
    if ((fromId === a && toId === b) || (fromId === b && toId === a)) return 'none';
  }

  return 'unknown';
}

